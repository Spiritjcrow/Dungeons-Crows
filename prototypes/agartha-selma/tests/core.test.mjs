import assert from 'node:assert/strict';
import {MEMORY_LIMIT,createDreamachine,stepDreamachine,actDreamachine,observe,inferDirector,regionAt,terrainHeight,restoreDreamachine,exportDreamachine,resetMemory,inferenceInterface,WORLD_LIMITS} from '../core.mjs';
const seed=405;
const init=createDreamachine({seed});
assert.equal(init.schema,'dnc-selma-dreamachine/1');
assert.equal(observe(init).location,'frost-fjord');
assert.ok(Number.isFinite(terrainHeight(0,-80)));
assert.equal(regionAt(-80),'sunward-spire');
assert.equal(regionAt(-137),'great-fracture');
assert.equal(regionAt(-198),'second-crown');
assert.equal(inferenceInterface().networkCalls,false);
assert.equal(inferenceInterface().externalSensors,false);
let a=structuredClone(init),b=structuredClone(init);
for(let i=0;i<1000;i++){
  a=stepDreamachine(a,{forward:1,dt:.05});
  b=stepDreamachine(b,{forward:1,dt:.05});
}
assert.deepEqual(a,b,'same seed and input must reproduce exact state');
assert.ok(a.player.z<WORLD_LIMITS.maxZ);
assert.ok(a.visited.includes('sunward-spire'));
assert.ok(a.visited.includes('great-fracture'));
assert.ok(a.visited.includes('second-crown'));
assert.ok(a.memory.length<=MEMORY_LIMIT);
assert.ok(inferDirector(a).every(x=>x.score>=0&&x.score<=6));
for(let i=0;i<150;i++)a=actDreamachine(a,'survey');
assert.equal(a.memory.length,MEMORY_LIMIT,'memory must cap at ninety-six entries');
let restored=restoreDreamachine(exportDreamachine(a));assert.deepEqual(restored,a);
assert.throws(()=>restoreDreamachine('{}'),/Invalid/);
assert.throws(()=>restoreDreamachine({...a,player:{...a.player,x:NaN}}),/Invalid/);
let near=createDreamachine({seed});near.player.x=6;near.player.z=-187;near.player.y=terrainHeight(6,-187);
assert.equal(observe(near).nearTreasure,true);
const claimed=actDreamachine(near,'interact');assert.equal(claimed.player.loot,1);assert.equal(claimed.flags.treasureClaimed,true);
const twice=actDreamachine(claimed,'interact');assert.equal(twice.player.loot,1,'same cache cannot be collected twice');
const cleared=resetMemory(twice);assert.equal(cleared.memory.length,0);assert.equal(cleared.player.loot,1);
const anomaly=actDreamachine(init,'dream');assert.ok(anomaly.dm.dream>0 && anomaly.dm.dream<=.78);
assert.equal(anomaly.player.y,init.player.y,'dream rendering never alters collision');
const guarded=stepDreamachine(anomaly,{forward:9999,dt:5000,turn:9999});assert.ok(Math.abs(guarded.player.z-anomaly.player.z)<2,'step and speed capped');
assert.equal(guarded.player.health,100);
console.log('core.test.mjs: deterministic input, environmental inference, bounded memory, treasure persistence, safe morphing PASS');